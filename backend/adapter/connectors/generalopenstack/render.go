package generalopenstack

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"

	"github.com/Alberta2514640/clutter/backend/adapter/connectors"
	"github.com/Alberta2514640/clutter/backend/api/generic/hclsafe"
)

// Output names. An id output maps a node id to the cloud's id for it; Apply
// reads these back from the run's log.
const (
	outputIDPrefix      = "id_"
	outputAddressPrefix = "address_"
)

// Resource and data source types, as provider 3.4 names them.
const (
	tInstance     = "openstack_compute_instance_v2"
	tNetwork      = "openstack_networking_network_v2"
	tSubnet       = "openstack_networking_subnet_v2"
	tRouter       = "openstack_networking_router_v2"
	tRouterIface  = "openstack_networking_router_interface_v2"
	tSecgroup     = "openstack_networking_secgroup_v2"
	tSecgroupRule = "openstack_networking_secgroup_rule_v2"
	tFloatingIP   = "openstack_networking_floatingip_v2"
	tFloatingAsoc = "openstack_networking_floatingip_associate_v2"
	tPort         = "openstack_networking_port_v2"
	tVolume       = "openstack_blockstorage_volume_v3"
	tVolumeAttach = "openstack_compute_volume_attach_v2"
	tImage        = "openstack_images_image_v2"
	tKeypair      = "openstack_compute_keypair_v2"

	externalAddr = "external"
	imageAddr    = "image"
	// routerAddr is the deployment's one router; no block's address (addr)
	// can be it.
	routerAddr = "deployment"
)

// peerAddr is the address of the security group that lets the VMs that get a
// VM's address reach it. It starts with p_, so it is never a block's address.
func peerAddr(nodeID string) string { return "p_" + nodeID }

// tags marks a Neutron resource as the deployment's, as the AWS provider's
// default tags do there; metadata does the same on a server or a volume.
func (m model) tags() string {
	return list([]string{str("ManagedBy=Clutter"), str("ClutterDeployment=" + m.deploymentID)})
}

func (m model) metadata() string {
	return "{ ManagedBy = " + str("Clutter") + ", ClutterDeployment = " + str(m.deploymentID) + " }"
}

// versionsFile pins the provider and leaves its block empty: the provider
// reads the run's OS_* variables.
func versionsFile() []byte {
	return []byte(`# Generated by Clutter. Do not edit.
terraform {
  required_providers {
    openstack = {
      source  = "` + providerSource + `"
      version = "` + providerVersion + `"
    }
  }
}

provider "openstack" {}
`)
}

// renderFiles turns a checked model into Terraform files.
func renderFiles(m model) map[string][]byte {
	return map[string][]byte{
		"versions.tf": versionsFile(),
		"main.tf":     renderMain(m),
		"outputs.tf":  renderOutputs(m),
	}
}

// addr is a block's Terraform address: its node id, which may start with a
// digit, behind a fixed letter. Renaming a block keeps its address.
func addr(nodeID string) string { return "b_" + nodeID }

func ref(parts ...string) string { return strings.Join(parts, ".") }

// str is an HCL string literal. Every value reaching it is already checked
// against a pattern or allow-list; escaping is the second guard.
func str(s string) string { return `"` + hclsafe.Escape(s) + `"` }

func list(items []string) string { return "[" + strings.Join(items, ", ") + "]" }

func renderMain(m model) []byte {
	var f file
	if m.externalNetwork != "" {
		d := f.block("data", tNetwork, externalAddr)
		d.set("name", str(m.externalNetwork))
		d.set("external", "true")
	}
	if len(m.vms) > 0 {
		d := f.block("data", tImage, imageAddr)
		d.set("name_regex", str("^"+regexp.QuoteMeta(m.image)))
		d.set("most_recent", "true")
	}

	// One router for the deployment: it joins every network whose VMs may
	// reach the internet, so they also reach each other.
	if m.anyRouted() {
		r := f.block("resource", tRouter, routerAddr)
		r.set("name", str(m.prefix+"-router"))
		r.set("external_network_id", ref("data", tNetwork, externalAddr, "id"))
		r.set("tags", m.tags())
	}

	for _, n := range m.networks {
		a := addr(n.id)
		r := f.block("resource", tNetwork, a)
		r.set("name", str(n.name))
		r.set("admin_state_up", "true")
		r.set("tags", m.tags())

		r = f.block("resource", tSubnet, a)
		r.set("name", str(n.name))
		r.set("network_id", ref(tNetwork, a, "id"))
		r.set("cidr", str(n.cidr))
		r.set("ip_version", "4")
		r.set("tags", m.tags())

		if n.routed {
			r = f.block("resource", tRouterIface, a)
			r.set("router_id", ref(tRouter, routerAddr, "id"))
			r.set("subnet_id", ref(tSubnet, a, "id"))
		}
	}

	for _, fw := range m.firewalls {
		a := addr(fw.id)
		r := f.block("resource", tSecgroup, a)
		r.set("name", str(fw.name))
		r.set("tags", m.tags())
		for _, rl := range fw.rules {
			r := f.block("resource", tSecgroupRule, a+ruleSuffix(rl))
			r.set("security_group_id", ref(tSecgroup, a, "id"))
			r.set("direction", str("ingress"))
			r.set("ethertype", str(fw.ethertype))
			r.set("protocol", str(protocol(rl, fw.ethertype)))
			if rl.Protocol != connectors.ProtocolICMP {
				r.set("port_range_min", strconv.Itoa(rl.FromPort))
				r.set("port_range_max", strconv.Itoa(rl.ToPort))
			}
			r.set("remote_ip_prefix", str(fw.source))
		}
	}

	// VMs that get another VM's address may reach it: every protocol and
	// port, from each of their addresses (one per network) only. Its own
	// group, beside the VM's firewalls; Neutron's default egress rules stay.
	byID := map[string]vm{}
	for _, v := range m.vms {
		byID[v.id] = v
	}
	for _, v := range m.vms {
		if len(v.reachedBy) == 0 {
			continue
		}
		a := peerAddr(v.id)
		r := f.block("resource", tSecgroup, a)
		// A block name holds no dot, so this name is never a firewall's.
		r.set("name", str(v.name+".peers"))
		r.set("tags", m.tags())
		for _, src := range v.reachedBy {
			for i := range byID[src].networks {
				r := f.block("resource", tSecgroupRule, fmt.Sprintf("%s_from_%s_%d", a, src, i))
				r.set("security_group_id", ref(tSecgroup, a, "id"))
				r.set("direction", str("ingress"))
				r.set("ethertype", str("IPv4"))
				r.set("remote_ip_prefix", `"${`+ref(tInstance, addr(src), fmt.Sprintf("network[%d]", i), "fixed_ip_v4")+`}/32"`)
			}
		}
	}

	for _, v := range m.vms {
		if v.sshKey == "" {
			continue
		}
		// Marked sensitive only to keep the key out of the run's log.
		r := f.block("resource", tKeypair, addr(v.id))
		r.set("name", str(v.name))
		r.set("public_key", "sensitive("+str(v.sshKey)+")")
	}

	for _, v := range m.vms {
		a := addr(v.id)
		r := f.block("resource", tInstance, a)
		r.set("name", str(v.name))
		r.set("image_id", ref("data", tImage, imageAddr, "id"))
		r.set("flavor_name", str(v.flavor))
		if v.sshKey != "" {
			r.set("key_pair", ref(tKeypair, a, "name"))
		}
		r.set("metadata", m.metadata())
		switch {
		case v.userDataExpr != "":
			// The values the VM's connections hand it, then its startup
			// script as base64 (connectors.StartupHCL). A secret makes the
			// argument sensitive, so Terraform never prints it; the provider
			// keeps only a hash of user data in state.
			if v.sensitive {
				r.set("user_data", "sensitive("+v.userDataExpr+")")
			} else {
				r.set("user_data", v.userDataExpr)
			}
		case v.userData != "":
			// The startup script reaches the file only as base64; Terraform
			// decodes it, and Nova hands it to cloud-init, which runs it once
			// as root at first boot. A changed script builds a new server.
			r.set("user_data", "base64decode("+str(v.userData)+")")
		}
		var groups []string
		for _, id := range v.firewalls {
			groups = append(groups, ref(tSecgroup, addr(id), "name"))
		}
		if len(v.reachedBy) > 0 {
			groups = append(groups, ref(tSecgroup, peerAddr(v.id), "name"))
		}
		if len(groups) > 0 {
			r.set("security_groups", list(groups))
		}
		subnets := make([]string, len(v.networks))
		for i, id := range v.networks {
			r.nested("network").set("uuid", ref(tNetwork, addr(id), "id"))
			subnets[i] = ref(tSubnet, addr(id))
		}
		// The subnet must exist before Nova asks Neutron for the VM's port.
		r.set("depends_on", list(subnets))

		if v.public {
			r := f.block("resource", tFloatingIP, a)
			r.set("pool", ref("data", tNetwork, externalAddr, "name"))
			r.set("description", str(v.name))
			r.set("tags", m.tags())

			d := f.block("data", tPort, a)
			d.set("device_id", ref(tInstance, a, "id"))
			d.set("network_id", ref(tInstance, a, "network[0]", "uuid"))

			r = f.block("resource", tFloatingAsoc, a)
			r.set("floating_ip", ref(tFloatingIP, a, "address"))
			r.set("port_id", ref("data", tPort, a, "id"))
			// The VM's first network must reach the external network first.
			r.set("depends_on", list([]string{ref(tRouterIface, addr(v.networks[0]))}))
		}
	}

	for _, vol := range m.volumes {
		a := addr(vol.id)
		r := f.block("resource", tVolume, a)
		r.set("name", str(vol.name))
		r.set("size", strconv.FormatInt(vol.sizeGB, 10))
		r.set("metadata", m.metadata())
		if vol.vm != "" {
			r := f.block("resource", tVolumeAttach, a)
			r.set("instance_id", ref(tInstance, addr(vol.vm), "id"))
			r.set("volume_id", ref(tVolume, a, "id"))
		}
	}
	return f.bytes()
}

// ruleSuffix keys a rule's address by its content, so changing one entry of
// an ingress list does not re-create the others.
func ruleSuffix(r connectors.IngressRule) string {
	if r.Protocol == connectors.ProtocolICMP {
		return "_icmp"
	}
	return fmt.Sprintf("_%s_%d_%d", r.Protocol, r.FromPort, r.ToPort)
}

// protocol is a rule's protocol as Neutron names it: ICMP for IPv6 sources is
// "ipv6-icmp".
func protocol(r connectors.IngressRule, ethertype string) string {
	if r.Protocol == connectors.ProtocolICMP && ethertype == "IPv6" {
		return "ipv6-icmp"
	}
	return r.Protocol
}

func renderOutputs(m model) []byte {
	var f file
	out := func(name, value string) { f.block("output", name).set("value", value) }
	for _, n := range m.networks {
		out(outputIDPrefix+n.id, ref(tNetwork, addr(n.id), "id"))
	}
	for _, fw := range m.firewalls {
		out(outputIDPrefix+fw.id, ref(tSecgroup, addr(fw.id), "id"))
	}
	for _, v := range m.vms {
		out(outputIDPrefix+v.id, ref(tInstance, addr(v.id), "id"))
		if v.public {
			out(outputAddressPrefix+v.id, ref(tFloatingIP, addr(v.id), "address"))
		}
		// What the deploy panel shows the user (connectors.ReadResults).
		if key, ok := connectors.ResultOutputName(v.id, connectors.ResultPrivateAddress); ok {
			out(key, ref(tInstance, addr(v.id), "access_ip_v4"))
		}
		if key, ok := connectors.ResultOutputName(v.id, connectors.ResultPublicAddress); ok && v.public {
			out(key, ref(tFloatingIP, addr(v.id), "address"))
		}
	}
	for _, vol := range m.volumes {
		out(outputIDPrefix+vol.id, ref(tVolume, addr(vol.id), "id"))
	}
	// What a split deployment's other clouds get: a public VM's address.
	for _, e := range m.exports {
		out(connectors.CrossOutputName(e.key, connectors.ValueAddress), ref(tFloatingIP, addr(e.vm), "address"))
	}
	return f.bytes()
}

// file and body write HCL in the layout terraform fmt produces: two-space
// indents, the equals signs of neighbouring attributes aligned, and a blank
// line around nested blocks and between top-level blocks.
type file struct{ blocks []*block }

type block struct {
	typ    string
	labels []string
	body   body
}

type body struct{ items []item }

type item struct {
	key, expr string
	nested    *block
}

func (f *file) block(typ string, labels ...string) *body {
	b := &block{typ: typ, labels: labels}
	f.blocks = append(f.blocks, b)
	return &b.body
}

func (b *body) set(key, expr string) { b.items = append(b.items, item{key: key, expr: expr}) }

func (b *body) nested(typ string) *body {
	n := &block{typ: typ}
	b.items = append(b.items, item{nested: n})
	return &n.body
}

func (f *file) bytes() []byte {
	var w strings.Builder
	w.WriteString("# Generated by Clutter. Do not edit.\n")
	for _, b := range f.blocks {
		w.WriteString("\n")
		b.write(&w, 0)
	}
	return []byte(w.String())
}

func (b *block) write(w *strings.Builder, depth int) {
	ind := strings.Repeat("  ", depth)
	w.WriteString(ind + b.typ)
	for _, l := range b.labels {
		w.WriteString(" " + str(l))
	}
	w.WriteString(" {\n")
	items := b.body.items
	for i := 0; i < len(items); {
		if i > 0 {
			w.WriteString("\n")
		}
		if items[i].nested != nil {
			items[i].nested.write(w, depth+1)
			i++
			continue
		}
		j, width := i, 0
		for ; j < len(items) && items[j].nested == nil; j++ {
			width = max(width, len(items[j].key))
		}
		for k := i; k < j; k++ {
			fmt.Fprintf(w, "%s  %-*s = %s\n", ind, width, items[k].key, items[k].expr)
		}
		i = j
	}
	w.WriteString(ind + "}\n")
}
